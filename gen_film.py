"""generates turbor/filmplay.inc: the cycle exact player of the FONY film (Z80 mode, SCREEN 5, 16 colours of the MSX2 palette).
One PCM sample every 224 Z80 cycles; in every sample one 'span' of the picture is written: a record of the stream = VRAM address (2 bytes) + 7 pixel pairs (14 pixels).
Eight samples make a group (the 8th has 6 data bytes and carries the loop control).  A frame of the stream = GA, GB (bytes) + GA groups for VRAM lines 0..127 (R#14 = 0) + GB groups for lines 128.. (R#14 = 1);
GA = 255: the next frame is at the start of the next bank, GA = 254: the end.  Then 3 housekeeping samples (key, audio pointer, audio bank).
Registers: HL = stream, DE = audio, C = 98h (inc c / dec c for the address bytes), IXL = loop counter."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_clip as G
from gen_clip import Sample, PERIOD, CORR, pad_instrs, lines

GA, GB = 50, 6                                   # (the intro film: the groups per frame are in the stream now; these are for filmenc)
KEEP = 'film_keep'


def group(label, loop):
    for i in range(8):
        s = Sample(label if i == 0 else None)
        s.audio()
        s.add('inc c', 5)
        s.add('outi', 19)
        s.add('outi', 19)
        s.add('dec c', 5)
        if i < 7:
            s.video(7)
        else:
            s.video(6)
            s.tailadd('dec ixl', 10)
            s.tailadd('jp nz,%s' % loop, 11)
        s.emit()


def head():
    s = Sample('film_frame'); s.audio()
    for x, c in (('ld a,(hl)', 8), ('inc hl', 7), ('cp 0xFF', 8), ('jp z,film_bank', 11), ('cp 0xFE', 8), ('jp z,film_end', 11), ('ld ixl,a', 10), ('ld a,(hl)', 8), ('inc hl', 7), ('ld (fl_gb),a', 14)):
        s.add(x, c)
    s.emit()


def region(label, r14, load):
    s = Sample(label)
    s.audio()
    s.add('ld a,%d' % r14, 8)
    s.add('out (0x99),a', 13)
    s.add('ld a,0x8E', 8)
    s.add('out (0x99),a', 13)
    if load:
        s.add('ld a,(fl_gb)', 14)
        s.add('ld ixl,a', 10)
    s.emit()


def housekeeping():
    # H1: the key (SPACE) and the stream pointer saved (H2 / H3 use HL)
    s = Sample('film_hk'); s.audio()
    s.add('ld (fl_sp),hl', 17)
    s.add('in a,(0xAA)', 13)
    s.add('and 0xF0', 8)
    s.add('or 8', 8)
    s.add('out (0xAA),a', 13)
    s.add('in a,(0xA9)', 13)
    s.add('and 1', 8)
    s.add('jp z,film_exit', 11)
    s.emit(adj=4)
    # H2: the audio pointer: D >= B8h: the next bank (16 bit) and DE - 3800h
    s = Sample(); s.audio()
    for t, c in (('ld a,d', 5), ('cp 0xB8', 8), ('sbc a,a', 5), ('cpl', 5), ('and 0x38', 8), ('ld b,a', 5), ('ld a,d', 5), ('sub b', 5), ('ld d,a', 5), ('ld a,b', 5),
                 ('rlca', 5), ('rlca', 5), ('rlca', 5), ('and 1', 8), ('ld hl,(au_bank)', 17), ('add a,l', 5), ('ld l,a', 5), ('ld a,h', 5), ('adc a,0', 8), ('ld h,a', 5),
                 ('ld (au_bank),hl', 17)):
        s.add(t, c)
    s.emit()
    # H3: the audio bank registers, the stream pointer back; next frame
    s = Sample(); s.audio()
    for t, c in (('ld hl,(au_bank)', 17), ('ld a,l', 5), ('ld (0x7000),a', 14), ('ld a,h', 5), ('ld (0x7001),a', 14), ('ld hl,(fl_sp)', 17)):
        s.add(t, c)
    s.tailadd('jp film_frame', 11)
    s.emit(adj=1)
    # the next bank of the stream
    s = Sample('film_bank'); s.cyc = 62            # (no audio of its own: this is the rest of the sample of the frame head, which jumped here after 62 cycles)
    for t, c in (('ld hl,(fl_bank)', 17), ('inc hl', 7), ('ld (fl_bank),hl', 17), ('ld a,l', 5), ('ld (0x6000),a', 14), ('ld a,h', 5), ('ld (0x6001),a', 14), ('ld hl,0x4000', 11)):
        s.add(t, c)
    s.tailadd('jp film_frame', 11)
    s.emit()


def gen():
    lines.append('; generated by gen_film.py: the cycle exact span player (Z80 mode, SCREEN 5)')
    head()
    region(None, 0, False)
    group('film_ga', 'film_ga')
    region(None, 1, True)
    group('film_gb', 'film_gb')
    housekeeping()


if __name__ == '__main__':
    gen()
    open(os.path.join(HERE, 'filmplay.inc'), 'w').write('\n'.join(lines) + '\n')
    print('filmplay.inc written:', len(lines), 'lines')
